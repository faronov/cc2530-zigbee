#!/usr/bin/env python3
"""Derive the SDCC-order CC2530 script for the upstream-based profile.

The frozen ordered script (cc2530-sdcc-order-pack.ld) was generated from the
older upstream cc2530.ld.  Current upstream cc2530.ld differs from that base
only by three section rules (efc84d8b4): .mcs51.code.rodata in .text,
.mcs51.xdata.init in .data and .mcs51.xdata.bss in .bss.  Apply exactly those
rules and let every ordered `*/m.o(.bss.X)` entry also match the upstream name
`.mcs51.xdata.bss.X`, so the SDCC XDATA order is kept under either naming.
usage: derive_up_ld.py FROZEN_ORDERED_LD UPSTREAM_CC2530_LD OUT
"""
import re, sys

frozen, upstream, out = sys.argv[1:4]
ld = open(frozen).read()
up = open(upstream).read()
for rule in ('*(.mcs51.code.rodata .mcs51.code.rodata.*)',
             '*(.mcs51.xdata.init .mcs51.xdata.init.*)',
             '*(.mcs51.xdata.bss .mcs51.xdata.bss.*)'):
    assert rule in up, rule
    assert rule not in ld, rule

def once(text, old, new):
    assert text.count(old) == 1, old
    return text.replace(old, new)

ld = once(ld, '    *(.rodata .rodata.*)\n  } > CODE',
          '    *(.rodata .rodata.*)\n    *(.mcs51.code.rodata .mcs51.code.rodata.*)\n  } > CODE')
ld = once(ld, '    *(.data .data.*)\n    __mcs51_data_end = .;',
          '    *(.data .data.*)\n    *(.mcs51.xdata.init .mcs51.xdata.init.*)\n    __mcs51_data_end = .;')
ld = once(ld, '    *(.bss .bss.*) *(COMMON)\n  } > XRAM',
          '    *(.bss .bss.*)\n    *(.mcs51.xdata.bss .mcs51.xdata.bss.*)\n    *(COMMON)\n  } > XRAM')
n = 0
def alias(m):
    global n
    n += 1
    return f'{m.group(1)}(.bss.{m.group(2)} .mcs51.xdata.bss.{m.group(2)})'
ld = re.sub(r'^(    \*/\w+\.o)\(\.bss\.(\S+)\)$', alias, ld, flags=re.M)
ld = ld.replace('/* GENERATED by gen_order_ld.py: study-only SDCC-order XDATA profile */',
                '/* DERIVED by derive_up_ld.py from the frozen SDCC-order profile for current upstream section names */')
open(out, 'w').write(ld)
print('ordered entries aliased', n)
